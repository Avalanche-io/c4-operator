package main

import (
	"fmt"
	"math"
	"os"

	"sigs.k8s.io/yaml"
)

// The scenario spec of hack/hudmock (spec.go there), as far as a grid
// point fills it. The types mirror that file's JSON names, so the YAML
// written here loads with hudmock's LoadSpec. A grid point is a
// statistical description, so the mapping is approximate where hudmock
// has a richer model: every shot becomes one pipeline whose stages are
// the point's DAG levels, and the point's arrival pattern becomes
// arrival windows on the projects' home clocks.
type xSpec struct {
	Name      string               `json:"name"`
	Title     string               `json:"title"`
	Summary   string               `json:"summary"`
	Seed      int64                `json:"seed"`
	Start     string               `json:"start"`
	Clock     string               `json:"clock"`
	Sites     []xSite              `json:"sites"`
	Pools     []xPool              `json:"pools"`
	Projects  []xProject           `json:"projects"`
	Pipelines map[string]xPipeline `json:"pipelines"`
	Arrivals  []xArrival           `json:"arrivals"`
}

type xSite struct {
	Name string `json:"name"`
	Kind string `json:"kind"`
	TZ   string `json:"tz"`
}

type xPool struct {
	Name         string  `json:"name"`
	Site         string  `json:"site"`
	Class        string  `json:"class"`
	Nodes        int     `json:"nodes"`
	SlotsPerNode int     `json:"slotsPerNode"`
	Cost         float64 `json:"costPerSlotHour"`
	FlakyNodes   int     `json:"flakyNodes,omitempty"`
	Burst        *xBurst `json:"burst,omitempty"`
}

type xBurst struct {
	MaxNodes      int     `json:"maxNodes"`
	Provisioning  string  `json:"provisioning"`
	Cost          float64 `json:"costPerSlotHour"`
	Spot          bool    `json:"spot,omitempty"`
	Interruptions float64 `json:"interruptionsPerNodeHour,omitempty"`
}

type xQuota struct {
	Nominal int  `json:"nominal"`
	Borrow  *int `json:"borrow,omitempty"`
}

type xProject struct {
	Name        string            `json:"name"`
	Home        string            `json:"home"`
	Quotas      map[string]xQuota `json:"quotas,omitempty"`
	BurstBudget float64           `json:"burstBudgetPerDay"`
	LateCost    float64           `json:"lateCostPerHour"`
}

type xPipeline struct {
	Stages []xStage `json:"stages"`
}

type xStage struct {
	Name     string   `json:"name"`
	After    []string `json:"after,omitempty"`
	Pools    []string `json:"pools"`
	Cost     string   `json:"cost"`
	Spread   float64  `json:"spread"`
	Expand   string   `json:"expand,omitempty"`
	Heavy    float64  `json:"heavy,omitempty"`
	FailRate float64  `json:"failRate,omitempty"`
}

type xArrival struct {
	Name     string   `json:"name"`
	Project  string   `json:"project"`
	Kind     string   `json:"kind"`
	Pipeline string   `json:"pipeline,omitempty"`
	PerDay   float64  `json:"perDay,omitempty"`
	Window   []string `json:"window"`
	Days     string   `json:"days"`
	Due      string   `json:"due,omitempty"`
	Frames   []int    `json:"frames,omitempty"`
	Ranks    []int    `json:"ranks,omitempty"`
	Hours    string   `json:"hours,omitempty"`
	Pools    []string `json:"pools,omitempty"`
}

func dur(sec float64) string { return fmt.Sprintf("%ds", int(math.Round(sec))) }

// writeSpec writes a point as a scenario spec.
func writeSpec(pt Point, seed uint64, path string) error {
	w := build(pt, seed)
	sp := xSpec{
		Name: "stress-" + pt.Name, Title: "Stress point " + pt.Name, Seed: int64(seed),
		Summary: "Generated by hack/stress from " + pt.encode(),
		Start:   "2026-10-19T" + map[int]string{0: "00:00", 1: "16:00", 2: "13:00", 3: "16:00"}[int(pt.Arrivals)%4], Clock: "UTC",
		Sites:     []xSite{{Name: "studio", Kind: "onprem", TZ: "UTC"}, {Name: "cloud", Kind: "cloud", TZ: "UTC"}},
		Pipelines: map[string]xPipeline{},
	}
	for _, p := range w.pools {
		xp := xPool{Name: p.name, Site: "studio", Class: p.class, Nodes: p.nodes, SlotsPerNode: p.spn}
		if pt.NodeFaults > 0 && p.burst == nil {
			xp.FlakyNodes = max(1, int(math.Round(pt.NodeFaults*float64(p.nodes))))
		}
		if b := p.burst; b != nil {
			xp.Site, xp.SlotsPerNode, xp.Cost = "cloud", 1, b.price
			xp.Burst = &xBurst{MaxNodes: b.max, Provisioning: dur(b.delay), Cost: b.price, Spot: b.interrupt > 0, Interruptions: b.interrupt}
		}
		sp.Pools = append(sp.Pools, xp)
	}
	for _, pr := range w.projects {
		xp := xProject{Name: pr.name, Home: "studio", BurstBudget: math.Round(pr.budget), LateCost: math.Round(pr.lateCost)}
		if len(pr.nominal) > 0 {
			xp.Quotas = map[string]xQuota{}
			for pool, n := range pr.nominal {
				q := xQuota{Nominal: n}
				if pr.borrow >= 0 {
					b := pr.borrow
					q.Borrow = &b
				}
				xp.Quotas[pool] = q
			}
		}
		sp.Projects = append(sp.Projects, xp)
	}
	depth, width := max(1, int(pt.Depth)), max(1, int(pt.Width))
	for _, class := range []string{"cpu", "gpu"} {
		pools := poolsOf(w, class)
		if _, ok := w.pools0(pools[0]); !ok {
			continue
		}
		var st []xStage
		var prev []string
		d, wd := depth, width
		if class == "gpu" {
			d, wd = 1, 1
		}
		for l := range d {
			n := wd
			if l == d-1 {
				n = 1
			}
			var names []string
			for k := range n {
				name := fmt.Sprintf("s%d%c", l, 'a'+k)
				cost := pt.UnitMin * minute * stageCost[min(l, len(stageCost)-1)]
				if class == "gpu" {
					cost /= 3
				}
				s := xStage{Name: name, After: prev, Pools: pools, Cost: dur(cost), Spread: pt.Spread, Heavy: pt.Heavy, FailRate: pt.FailRate}
				if pt.Expand > 0 {
					s.Expand = "rib"
				}
				st = append(st, s)
				names = append(names, name)
			}
			prev = names
		}
		sp.Pipelines[class] = xPipeline{Stages: st}
	}
	window := map[int][]string{0: {"00:00", "23:59"}, 1: {"17:00", "23:30"}, 2: {"14:00", "18:00"}, 3: {"17:00", "23:30"}}[int(pt.Arrivals)%4]
	shots := map[string]map[string]float64{}
	ml := map[string]float64{}
	for _, js := range w.jobs {
		switch {
		case js.kind == "ml":
			ml[js.project]++
		case js.level == 0 && !js.gate:
			if shots[js.project] == nil {
				shots[js.project] = map[string]float64{}
			}
			shots[js.project][js.class]++
		}
	}
	due := fmt.Sprintf("+%.0fh", math.Max(1, pt.Tightness*pt.UnitMin*minute*60/hour/8))
	days := math.Max(1, pt.Days)
	for _, pr := range w.projects {
		for _, class := range []string{"cpu", "gpu"} {
			if n := shots[pr.name][class] / days; n > 0 {
				sp.Arrivals = append(sp.Arrivals, xArrival{Name: pr.name + "-" + class, Project: pr.name, Kind: "shot", Pipeline: class,
					PerDay: math.Round(n*10) / 10, Window: window, Days: "daily", Due: due, Frames: []int{60, 1, 1000}})
			}
		}
		if n := ml[pr.name] / days; n > 0 {
			sp.Arrivals = append(sp.Arrivals, xArrival{Name: pr.name + "-ml", Project: pr.name, Kind: "ml", PerDay: math.Round(n*10) / 10,
				Window: window, Days: "daily", Ranks: []int{1, 2, 4, 8}[:min(4, max(1, int(math.Log2(math.Max(1, pt.Ranks)))+1))],
				Hours: dur(math.Max(hour, 8*pt.UnitMin*minute)), Pools: poolsOf(w, "gpu")})
		}
	}
	b, err := yaml.Marshal(sp)
	if err != nil {
		return err
	}
	return os.WriteFile(path, b, 0o644)
}

func (w *workload) pools0(name string) (poolDef, bool) {
	for _, p := range w.pools {
		if p.name == name {
			return p, true
		}
	}
	return poolDef{}, false
}
