// runMCP serves the farm's MCP server: over stdio for a local agent, or
// over Streamable HTTP (stateless, JSON responses) for remote ones. It is
// a client of the HUD API; over HTTP each request's own bearer token is
// passed through, so every caller acts as itself.
func runMCP(args []string) error {
	fs := flag.NewFlagSet("mcp", flag.ExitOnError)
	hud := fs.String("hud", env("C4_HUD", "http://127.0.0.1:30080"), "the HUD's address")
	tokenFile := fs.String("token-file", "", "file holding the bearer token sent to the HUD (stdio mode; over HTTP each request's own token is used)")
	as := fs.String("as", "", "development only: the viewer to ask as, on a HUD started with --hud-dev-viewers")
	agent := fs.String("agent", "", "the agent's name; the farm's book records its controls as agent/NAME for the user")
	addr := fs.String("http", "", "serve Streamable HTTP on this address instead of stdio")
	toolsMD := fs.Bool("tools-md", false, "print the tool reference as markdown and exit")
	fs.Parse(args)
	mcpserver.Version = version

	token := ""
	if *tokenFile != "" {
		b, err := os.ReadFile(*tokenFile)
		if err != nil {
			return err
		}
		token = strings.TrimSpace(string(b))
	}
	if *toolsMD {
		return toolsMarkdown(os.Stdout)
	}
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()
	if *addr == "" {
		return mcpserver.New(&mcpserver.Client{Base: *hud, Token: token, As: *as, Agent: *agent}).Run(ctx, &mcp.StdioTransport{})
	}
	h := mcp.NewStreamableHTTPHandler(func(r *http.Request) *mcp.Server {
		c := &mcpserver.Client{Base: *hud, Token: token, As: *as, Agent: *agent}
		if t, ok := strings.CutPrefix(r.Header.Get("Authorization"), "Bearer "); ok {
			c.Token = t
		}
		return mcpserver.New(c)
	}, &mcp.StreamableHTTPOptions{Stateless: true, JSONResponse: true})
	srv := &http.Server{Addr: *addr, Handler: h, ReadHeaderTimeout: 10 * time.Second}
	go func() {
		<-ctx.Done()
		sctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
		defer cancel()
		srv.Shutdown(sctx)
	}()
	if err := srv.ListenAndServe(); err != nil && !errors.Is(err, http.ErrServerClosed) {
		return err
	}
	return nil
}

// toolsMarkdown writes the tool reference from the tools themselves: it
// lists them through an MCP client, so the schemas are the ones agents
// see.
func toolsMarkdown(w io.Writer) error {
	ctx := context.Background()
	srv := mcpserver.New(&mcpserver.Client{}) // no HUD: the fixed tools only, not a farm's c4_run_<tool>
	ct, st := mcp.NewInMemoryTransports()
	if _, err := srv.Connect(ctx, st, nil); err != nil {
		return err
	}
	cs, err := mcp.NewClient(&mcp.Implementation{Name: "docs", Version: "v1"}, nil).Connect(ctx, ct, nil)
	if err != nil {
		return err
	}
	defer cs.Close()
	res, err := cs.ListTools(ctx, nil)
	if err != nil {
		return err
	}
	fmt.Fprintln(w, "# MCP tool reference")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "Generated by `c4-operator mcp --tools-md` from the server's own tool list; do not edit by hand.")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "| tool | reads only | idempotent | destructive | summary |")
	fmt.Fprintln(w, "|---|---|---|---|---|")
	for _, t := range res.Tools {
		a := t.Annotations
		dest := a.DestructiveHint == nil || *a.DestructiveHint
		if a.ReadOnlyHint {
			dest = false
		}
		fmt.Fprintf(w, "| `%s` | %s | %s | %s | %s |\n", t.Name, yes(a.ReadOnlyHint), yes(a.ReadOnlyHint || a.IdempotentHint), yes(dest), firstSentence(t.Description))
	}
	for _, t := range res.Tools {
		fmt.Fprintf(w, "\n## %s\n\n%s\n\n", t.Name, t.Description)
		fmt.Fprintln(w, "Input:")
		fmt.Fprintln(w)
		fmt.Fprintln(w, "```json")
		b, _ := json.MarshalIndent(t.InputSchema, "", "  ")
		fmt.Fprintln(w, string(b))
		fmt.Fprintln(w, "```")
	}
	return nil
}

func yes(b bool) string {
	if b {
		return "yes"
	}
	return "no"
}

func firstSentence(s string) string {
	if i := strings.Index(s, ". "); i > 0 {
		return s[:i+1]
	}
	return s
}
